"""
PostgreSQL Adapter Package.

This package provides comprehensive PostgreSQL support for PyNext, organized into
logical submodules:

- core/: Essential adapter, URL parsing, types, caching
- pool/: Connection pool, queue, lifecycle, warmup, external poolers
- reliability/: Retry, circuit breaker, replica routing, degradation
- performance/: Timeout, query cache, coalescing, pipelining, batching, scaling
- observability/: Logging, metrics, Prometheus, OpenTelemetry, analyzer, monitor
- queries/: Query timeout, EXPLAIN, pagination, prepared statements, cancellation

Usage:
    # Simple
    from pynext.db.adapters import PostgresAdapter
    
    # New organized imports (recommended)
    from pynext.db.adapters.postgres.core import PostgresAdapter
    from pynext.db.adapters.postgres.reliability import RetryConfig, CircuitBreaker
    from pynext.db.adapters.postgres.observability import LogConfig, MetricsConfig
"""

