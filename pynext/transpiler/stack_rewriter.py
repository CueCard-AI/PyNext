def parse_stack_trace(stack_trace: str) -> ParsedStackTrace:
    """
    Parse a JavaScript stack trace into structured format.
    
    WHAT: Converts string stack trace to structured format.
    WHY: Enables programmatic rewriting of stack traces.
    HOW: Uses regex to parse different browser formats.
    WHO: Called by rewrite_stack_trace.
    WHEN: When processing JavaScript stack traces.
    WHERE: Part of stack trace rewriting.
    
    Supports formats:
    - Chrome/Edge: "at functionName (file.js:10:5)"
    - Firefox: "functionName@file.js:10:5"
    - Safari: "functionName@file.js:10:5" or "global code@file.js:10:5"
    - Node.js: "at functionName (file.js:10:5)"
    
    Args:
        stack_trace: JavaScript stack trace string
    
    Returns:
        ParsedStackTrace with error message and frames
    """
    lines = stack_trace.strip().split("\n")
    if not lines:
        return ParsedStackTrace(original=stack_trace)
    
    # First line is usually the error message
    error_message = lines[0]
    frames = []
    
    # Parse frames (skip first line)
    for line in lines[1:]:
        line = line.strip()
        if not line:
            continue
        
        frame = _parse_frame(line)
        if frame:
            frames.append(frame)
    
    return ParsedStackTrace(
        error_message=error_message,
        frames=frames,
        original=stack_trace,
    )


def _parse_frame(line: str) -> Optional[StackFrame]:
    """
    Parse a single stack frame line.
    
    WHAT: Extracts frame information from a stack trace line.
    WHY: Enables parsing of different browser formats.
    HOW: Uses regex patterns for Chrome, Firefox, Safari formats.
    WHO: Called by parse_stack_trace.
    WHEN: For each frame line in stack trace.
    WHERE: Part of stack trace parsing.
    
    Args:
        line: Stack frame line string
    
    Returns:
        StackFrame or None if line doesn't match any format
    """
    # Chrome/Edge/Node.js format: "at functionName (file.js:10:5)"
    # Handle URLs with colons: match file path up to the last colon before line number
    chrome_pattern = r"at\s+(?P<function>\S+)\s+\((?P<file>.+?):(?P<line>\d+):(?P<column>\d+)\)"
    match = re.search(chrome_pattern, line)
    if match:
        return StackFrame(
            function=match.group("function"),
            file=match.group("file"),
            line=int(match.group("line")),
            column=int(match.group("column")),
            raw=line,
        )
    
    # Firefox/Safari format: "functionName@file.js:10:5"
    # Handle URLs with colons
    firefox_pattern = r"(?P<function>[^@]+)@(?P<file>.+?):(?P<line>\d+):(?P<column>\d+)"
    match = re.search(firefox_pattern, line)
    if match:
        function = match.group("function").strip()
        if function == "global code":
            function = None
        return StackFrame(
            function=function if function else None,
            file=match.group("file"),
            line=int(match.group("line")),
            column=int(match.group("column")),
            raw=line,
        )
    
    # Chrome format without column: "at functionName (file.js:10)"
    chrome_no_col_pattern = r"at\s+(?P<function>\S+)\s+\((?P<file>.+?):(?P<line>\d+)\)"
    match = re.search(chrome_no_col_pattern, line)
    if match:
        return StackFrame(
            function=match.group("function"),
            file=match.group("file"),
            line=int(match.group("line")),
            column=None,
            raw=line,
        )
    
    # Firefox format without column: "functionName@file.js:10"
    firefox_no_col_pattern = r"(?P<function>[^@]+)@(?P<file>.+?):(?P<line>\d+)"
    match = re.search(firefox_no_col_pattern, line)
    if match:
        function = match.group("function").strip()
        if function == "global code":
            function = None
        return StackFrame(
            function=function if function else None,
            file=match.group("file"),
            line=int(match.group("line")),
            column=None,
            raw=line,
        )
    
    # Handle async functions: "at async functionName (file.js:10:5)"
    chrome_async_pattern = r"at\s+async\s+(?P<function>\S+)\s+\((?P<file>.+?):(?P<line>\d+):(?P<column>\d+)\)"
    match = re.search(chrome_async_pattern, line)
    if match:
        return StackFrame(
            function=match.group("function"),
            file=match.group("file"),
            line=int(match.group("line")),
            column=int(match.group("column")),
            raw=line,
        )
    
    # Handle negative line numbers (edge case, but parse anyway)
    chrome_neg_pattern = r"at\s+(?P<function>\S+)\s+\((?P<file>.+?):(?P<line>-?\d+):(?P<column>-?\d+)\)"
    match = re.search(chrome_neg_pattern, line)
    if match:
        return StackFrame(
            function=match.group("function"),
            file=match.group("file"),
            line=int(match.group("line")),
            column=int(match.group("column")),
            raw=line,
        )
    
    return None


