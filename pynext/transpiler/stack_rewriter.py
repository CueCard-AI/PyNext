def rewrite_stack_trace(
    stack_trace: str,
    source_map: dict,
    source_file: Optional[str] = None,
) -> str:
    """
    Rewrite a JavaScript stack trace to show Python source locations.
    
    WHAT: Converts JavaScript stack trace to Python stack trace.
    WHY: Enables developers to debug Python code in browser.
    HOW: Parses JS stack, maps positions using source map, rewrites frames.
    WHO: Used by error handlers and debug tools.
    WHEN: When JavaScript errors occur in transpiled code.
    WHERE: Part of stack trace rewriting system.
    
    Args:
        stack_trace: JavaScript stack trace string
        source_map: V3 source map dictionary
        source_file: Optional Python source file name (if not in source map)
    
    Returns:
        Rewritten stack trace with Python locations
    
    Example:
        js_stack = "Error: Division by zero\\n    at divide (handler.js:15:8)"
        source_map = {...}  # From sourcemap.py
        python_stack = rewrite_stack_trace(js_stack, source_map)
        # → "Error: Division by zero\\n    at divide (handler.py:12:5)"
    """
    parsed = parse_stack_trace(stack_trace)
    if not parsed.frames:
        return stack_trace  # No frames to rewrite
    
    lookup = SourceMapLookup(source_map)
    
    # Get source file name
    if not source_file:
        sources = source_map.get("sources", [])
        source_file = sources[0] if sources else "source.py"
    
    # Rewrite frames
    rewritten_lines = [parsed.error_message]
    
    for frame in parsed.frames:
        if not frame.file or not frame.line:
            # Can't rewrite without file/line
            rewritten_lines.append(frame.raw)
            continue
        
        # Convert to 0-indexed for lookup
        gen_line = frame.line - 1
        gen_col = (frame.column - 1) if frame.column else 0
        
        # Phase 33.3: Handle zero/negative line numbers gracefully
        # Line 0 (1-indexed) becomes -1 (0-indexed), which is invalid
        # Negative line numbers are also invalid
        if gen_line < 0:
            rewritten_lines.append(frame.raw)  # Preserve original frame
            continue
        
        # Look up Python position
        mapped = lookup.lookup(gen_line, gen_col)
        
        if mapped:
            src_line, src_col, name = mapped
            # Convert back to 1-indexed
            src_line += 1
            src_col += 1
            
            # Use mapped function name if available, otherwise original
            function_name = name if name else frame.function
            
            # Rewrite frame
            if function_name:
                rewritten_lines.append(f"    at {function_name} ({source_file}:{src_line}:{src_col})")
            else:
                rewritten_lines.append(f"    at {source_file}:{src_line}:{src_col}")
        else:
            # No mapping found, use original
            rewritten_lines.append(frame.raw)
    
    return "\n".join(rewritten_lines)


def rewrite_stack_trace_from_file(
    stack_trace: str,
    source_map_path: str,
    source_file: Optional[str] = None,
) -> str:
    """
    Rewrite stack trace using source map from file.
    
    WHAT: Convenience function to load source map from file.
    WHY: Simplifies usage when source map is in a file.
    HOW: Loads source map JSON and calls rewrite_stack_trace.
    WHO: Used by error handlers that have source map files.
    WHEN: When source map is stored as a file.
    WHERE: Part of stack trace rewriting API.
    
    Args:
        stack_trace: JavaScript stack trace string
        source_map_path: Path to source map JSON file
        source_file: Optional Python source file name
    
    Returns:
        Rewritten stack trace with Python locations
    """
    try:
        with open(source_map_path, "r") as f:
            source_map = json.load(f)
        return rewrite_stack_trace(stack_trace, source_map, source_file)
    except Exception as e:
        # Return original if source map can't be loaded
        return stack_trace

